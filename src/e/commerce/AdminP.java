    // Method to check if Product ID already exists in the database
private boolean isProductIDExists(String productID) {
    try {
        Connection con = DBConnection.getConnection();
        PreparedStatement pst = con.prepareStatement("SELECT COUNT(*) FROM products WHERE product_id = ?");
        pst.setString(1, productID);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            return rs.getInt(1) > 0; // If count > 0, ID already exists
        }
    } catch (Exception e) {
        e.printStackTrace();
    }
    return false;
}

