    private void L_ADDMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_L_ADDMouseClicked
       
    String productid = txtPID.getText().trim();
    String category = txtCAT.getText().trim();
    String itemN = txtIN.getText().trim();
    String description = txtDes.getText().trim();
    String priceText = txtP.getText().trim();
    String quantityText = txtQ.getText().trim();
    String choose = (String) cmbStatus.getSelectedItem();

    // Validate user selection
    if (choose == "Choose") {
        JOptionPane.showMessageDialog(this, "Please select a status", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validate required fields
    if (productid.isEmpty() || category.isEmpty() || itemN.isEmpty() || 
        description.isEmpty() || priceText.isEmpty() || quantityText.isEmpty()) {
        JOptionPane.showMessageDialog(this, "All fields are required!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validate numeric fields (price & quantity)
    double price; int quantity;
    try {
        price = Double.parseDouble(priceText);
        quantity = Integer.parseInt(quantityText);
        
        if (price < 0 || quantity < 0) {
            JOptionPane.showMessageDialog(this, "Price and quantity must be positive numbers", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Price and quantity must be valid numbers", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    StatusT selectedUserType = StatusT.valueOf(choose.toUpperCase());

    try {
        Connection con = DBConnection.getConnection();

        // Validate image selection
        if (selectedImagePath == null || selectedImagePath.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select an image", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Insert into database
        String query = "INSERT INTO products (product_id, name, category, description, price, stock, image, status) VALUES (?,?,?,?,?,?,?,?)";
        PreparedStatement pst = con.prepareStatement(query);
        pst.setString(1, productid);
        pst.setString(2, itemN);
        pst.setString(3, category);
        pst.setString(4, description);
        pst.setDouble(5, price);
        pst.setInt(6, quantity);
        pst.setString(7, selectedImagePath); // Store file path
        pst.setString(8, selectedUserType.name());

        int rowsInserted = pst.executeUpdate();
        if (rowsInserted > 0) {
            JOptionPane.showMessageDialog(this, "Product added successfully!");
            table();
        } else {
            JOptionPane.showMessageDialog(this, "Product addition failed", "Error", JOptionPane.ERROR_MESSAGE);
        }

        pst.close();
        con.close();
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
        
    }//GEN-LAST:event_L_ADDMouseClicked

